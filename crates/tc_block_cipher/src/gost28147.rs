//! GOST 28147-89 64-bit block cipher, ported from Bouncy Castle's
//! `Gost28147Engine`.
//!
//! The cipher uses a fixed 256-bit key and one of several standardized S-boxes.
//! [`Gost28147Params`] owns validated, fixed-size copies of the key and S-box;
//! [`init`](tc_cipher_core::BlockCipherInit::init) expands the key into the engine.
//!
//! ```
//! use tc_cipher_core::{BlockCipher, BlockCipherInit, CipherDirection};
//! use tc_block_cipher::{Gost28147Engine, Gost28147Params};
//!
//! let key = [0u8; 32];
//! let params = Gost28147Params::new(&key)?;
//! let mut cipher = Gost28147Engine::new();
//! cipher.init(CipherDirection::Encrypt, &params)?;
//!
//! let mut output = [0u8; 8];
//! cipher.process_block(&[0u8; 8], &mut output)?;
//! # Ok::<(), tc_block_cipher::BlockCipherError>(())
//! ```

use crate::BlockCipherError;

mod engine;
mod params;

pub use engine::Gost28147Engine;
pub use params::Gost28147Params;

/// GOST 28147 key length in bytes (256 bits).
pub const GOST28147_KEY_BYTES: usize = 32;
/// GOST 28147 block length in bytes (64 bits).
pub const GOST28147_BLOCK_BYTES: usize = 8;
/// Number of entries in a GOST 28147 S-box (eight rows of sixteen nibbles).
pub const GOST28147_S_BOX_BYTES: usize = 128;

/// A standardized GOST 28147 S-box.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Gost28147SBox {
    /// Bouncy Castle's `Default` S-box (also `D-Test`).
    #[default]
    Default,
    /// Encryption test S-box (`E-Test`).
    EncryptionTest,
    /// CryptoPro encryption S-box A (`E-A`).
    EncryptionA,
    /// CryptoPro encryption S-box B (`E-B`).
    EncryptionB,
    /// CryptoPro encryption S-box C (`E-C`).
    EncryptionC,
    /// CryptoPro encryption S-box D (`E-D`).
    EncryptionD,
    /// Digest test S-box (`D-Test`, identical to `Default`).
    DigestTest,
    /// CryptoPro digest S-box A (`D-A`).
    DigestA,
}

impl Gost28147SBox {
    /// Bouncy Castle's canonical name for this S-box.
    pub const fn name(self) -> &'static str {
        match self {
            Self::Default => "Default",
            Self::EncryptionTest => "E-Test",
            Self::EncryptionA => "E-A",
            Self::EncryptionB => "E-B",
            Self::EncryptionC => "E-C",
            Self::EncryptionD => "E-D",
            Self::DigestTest => "D-Test",
            Self::DigestA => "D-A",
        }
    }

    pub(crate) const fn table(self) -> &'static [u8; GOST28147_S_BOX_BYTES] {
        match self {
            Self::Default | Self::DigestTest => &SBOX_DEFAULT,
            Self::EncryptionTest => &SBOX_E_TEST,
            Self::EncryptionA => &SBOX_E_A,
            Self::EncryptionB => &SBOX_E_B,
            Self::EncryptionC => &SBOX_E_C,
            Self::EncryptionD => &SBOX_E_D,
            Self::DigestA => &SBOX_D_A,
        }
    }
}

