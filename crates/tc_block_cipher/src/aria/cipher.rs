pub(super) fn key_schedule(for_encryption: bool, key: &[u8]) -> (AriaRoundKeys, usize) {
    let key_len_index = (key.len() >> 3) - 2;
    let ck1 = &C[key_len_index];
    let ck2 = &C[(key_len_index + 1) % 3];
    let ck3 = &C[(key_len_index + 2) % 3];

    let mut w0 = [0u8; ARIA_BLOCK_BYTES];
    let mut w1;
    let mut w2;
    let mut w3;

    w0.copy_from_slice(&key[..ARIA_BLOCK_BYTES]);
    w1 = w0;
    fo(&mut w1, ck1);
    for (destination, source) in w1.iter_mut().zip(&key[ARIA_BLOCK_BYTES..]) {
        *destination ^= *source;
    }

    w2 = w1;
    fe(&mut w2, ck2);
    xor(&mut w2, &w0);

    w3 = w2;
    fo(&mut w3, ck3);
    xor(&mut w3, &w1);

    let rounds = 12 + key_len_index * 2;
    let mut round_keys = [[0u8; ARIA_BLOCK_BYTES]; 17];

    round_keys[0] = key_schedule_round(&w0, &w1, 19);
    round_keys[1] = key_schedule_round(&w1, &w2, 19);
    round_keys[2] = key_schedule_round(&w2, &w3, 19);
    round_keys[3] = key_schedule_round(&w3, &w0, 19);

    round_keys[4] = key_schedule_round(&w0, &w1, 31);
    round_keys[5] = key_schedule_round(&w1, &w2, 31);
    round_keys[6] = key_schedule_round(&w2, &w3, 31);
    round_keys[7] = key_schedule_round(&w3, &w0, 31);

    round_keys[8] = key_schedule_round(&w0, &w1, 67);
    round_keys[9] = key_schedule_round(&w1, &w2, 67);
    round_keys[10] = key_schedule_round(&w2, &w3, 67);
    round_keys[11] = key_schedule_round(&w3, &w0, 67);

    round_keys[12] = key_schedule_round(&w0, &w1, 97);
    if rounds > 12 {
        round_keys[13] = key_schedule_round(&w1, &w2, 97);
        round_keys[14] = key_schedule_round(&w2, &w3, 97);
        if rounds > 14 {
            round_keys[15] = key_schedule_round(&w3, &w0, 97);
            round_keys[16] = key_schedule_round(&w0, &w1, 109);
        }
    }

    if !for_encryption {
        round_keys[..=rounds].reverse();
        for round_key in &mut round_keys[1..rounds] {
            diffuse(round_key);
        }
    }

    (round_keys, rounds)
}

pub(super) fn process_block(
    round_keys: &AriaRoundKeys,
    rounds: usize,
    input: &[u8; ARIA_BLOCK_BYTES],
    output: &mut [u8; ARIA_BLOCK_BYTES],
) {
    let mut state = *input;
    let mut round = 0;

    while round < rounds - 2 {
        fo(&mut state, &round_keys[round]);
        round += 1;
        fe(&mut state, &round_keys[round]);
        round += 1;
    }

    fo(&mut state, &round_keys[round]);
    round += 1;
    xor(&mut state, &round_keys[round]);
    round += 1;
    substitute_layer_2(&mut state);
    xor(&mut state, &round_keys[round]);

    *output = state;
}

fn key_schedule_round(
    word: &[u8; ARIA_BLOCK_BYTES],
    rotated_word: &[u8; ARIA_BLOCK_BYTES],
    rotation: usize,
) -> [u8; ARIA_BLOCK_BYTES] {
    let offset = rotation >> 3;
    let right = rotation & 7;
    let left = 8 - right;
    let mut round_key = [0u8; ARIA_BLOCK_BYTES];

    let mut high = usize::from(rotated_word[15 - offset]);
    for (index, destination) in round_key.iter_mut().enumerate() {
        let low = usize::from(rotated_word[index.wrapping_sub(offset) & 0x0f]);
        *destination = (((high << left) | (low >> right)) as u8) ^ word[index];
        high = low;
    }

    round_key
}

fn fo(state: &mut [u8; ARIA_BLOCK_BYTES], round_key: &[u8; ARIA_BLOCK_BYTES]) {
    xor(state, round_key);
    substitute_layer_1(state);
    diffuse(state);
}

fn fe(state: &mut [u8; ARIA_BLOCK_BYTES], round_key: &[u8; ARIA_BLOCK_BYTES]) {
    xor(state, round_key);
    substitute_layer_2(state);
    diffuse(state);
}

fn substitute_layer_1(state: &mut [u8; ARIA_BLOCK_BYTES]) {
    for chunk in state.chunks_exact_mut(4) {
        chunk[0] = SB1[usize::from(chunk[0])];
        chunk[1] = SB2[usize::from(chunk[1])];
        chunk[2] = SB3[usize::from(chunk[2])];
        chunk[3] = SB4[usize::from(chunk[3])];
    }
}

fn substitute_layer_2(state: &mut [u8; ARIA_BLOCK_BYTES]) {
    for chunk in state.chunks_exact_mut(4) {
        chunk[0] = SB3[usize::from(chunk[0])];
        chunk[1] = SB4[usize::from(chunk[1])];
        chunk[2] = SB1[usize::from(chunk[2])];
        chunk[3] = SB2[usize::from(chunk[3])];
    }
}

fn diffuse(state: &mut [u8; ARIA_BLOCK_BYTES]) {
    let [
        x0,
        x1,
        x2,
        x3,
        x4,
        x5,
        x6,
        x7,
        x8,
        x9,
        x10,
        x11,
        x12,
        x13,
        x14,
        x15,
    ] = *state;
    state[0] = x3 ^ x4 ^ x6 ^ x8 ^ x9 ^ x13 ^ x14;
    state[1] = x2 ^ x5 ^ x7 ^ x8 ^ x9 ^ x12 ^ x15;
    state[2] = x1 ^ x4 ^ x6 ^ x10 ^ x11 ^ x12 ^ x15;
    state[3] = x0 ^ x5 ^ x7 ^ x10 ^ x11 ^ x13 ^ x14;
    state[4] = x0 ^ x2 ^ x5 ^ x8 ^ x11 ^ x14 ^ x15;
    state[5] = x1 ^ x3 ^ x4 ^ x9 ^ x10 ^ x14 ^ x15;
    state[6] = x0 ^ x2 ^ x7 ^ x9 ^ x10 ^ x12 ^ x13;
    state[7] = x1 ^ x3 ^ x6 ^ x8 ^ x11 ^ x12 ^ x13;
    state[8] = x0 ^ x1 ^ x4 ^ x7 ^ x10 ^ x13 ^ x15;
    state[9] = x0 ^ x1 ^ x5 ^ x6 ^ x11 ^ x12 ^ x14;
    state[10] = x2 ^ x3 ^ x5 ^ x6 ^ x8 ^ x13 ^ x15;
    state[11] = x2 ^ x3 ^ x4 ^ x7 ^ x9 ^ x12 ^ x14;
    state[12] = x1 ^ x2 ^ x6 ^ x7 ^ x9 ^ x11 ^ x12;
    state[13] = x0 ^ x3 ^ x6 ^ x7 ^ x8 ^ x10 ^ x13;
    state[14] = x0 ^ x3 ^ x4 ^ x5 ^ x9 ^ x11 ^ x14;
    state[15] = x1 ^ x2 ^ x4 ^ x5 ^ x8 ^ x10 ^ x15;
}

fn xor(state: &mut [u8; ARIA_BLOCK_BYTES], value: &[u8; ARIA_BLOCK_BYTES]) {
    for (destination, source) in state.iter_mut().zip(value) {
        *destination ^= *source;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn diffusion_is_an_involution() {
        let original = [
            0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd,
            0xee, 0xff,
        ];
        let mut state = original;
        diffuse(&mut state);
        diffuse(&mut state);
        assert_eq!(state, original);
    }

    #[test]
    fn s_box_pairs_are_inverses() {
        for value in 0u8..=u8::MAX {
            assert_eq!(SB3[usize::from(SB1[usize::from(value)])], value);
            assert_eq!(SB1[usize::from(SB3[usize::from(value)])], value);
            assert_eq!(SB4[usize::from(SB2[usize::from(value)])], value);
            assert_eq!(SB2[usize::from(SB4[usize::from(value)])], value);
        }
    }
}
