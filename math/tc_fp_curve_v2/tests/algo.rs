use tc_bigint::PaddedBigUint;
use tc_ec_core_v2::algo::{
    AlgorithmError, clean_point, import_point, montgomery_trick, normalize_all, validate_point,
};
use tc_ec_core_v2::{CoordinateSystem, Curve, FieldElement, Point};
use tc_fp_curve_v2::named_curves::SECP256R1;
use tc_fp_curve_v2::{FpField, FpFieldElement, FpVarCurve};

const SYSTEMS: [CoordinateSystem; 4] = [
    CoordinateSystem::Affine,
    CoordinateSystem::Homogeneous,
    CoordinateSystem::Jacobian,
    CoordinateSystem::JacobianModified,
];

fn int(value: u8) -> PaddedBigUint {
    PaddedBigUint::from(value)
}

// y² = x³ + 2x + 2 over F17, of prime order 19, generated by (5, 1).
fn curve17(field: &FpField, system: CoordinateSystem) -> FpVarCurve<'_> {
    FpVarCurve::new(field, &int(2), &int(2), Some(int(19)), Some(int(1)))
        .unwrap()
        .with_coordinate_system(system)
}

fn elements<'a>(one: &FpFieldElement<'a>, count: usize) -> Vec<FpFieldElement<'a>> {
    let mut values = vec![one.clone()];
    while values.len() < count {
        let next = values.last().unwrap().add(one);
        values.push(next);
    }
    values
}

#[test]
fn import_point_moves_a_point_to_an_equivalent_curve_in_its_coordinate_system() {
    let field = FpField::new(int(17)).unwrap();
    for from in SYSTEMS {
        let source = curve17(&field, from);
        let p = source
            .create_point(&int(5), &int(1))
            .unwrap()
            .multiply(&int(5));
        for to in SYSTEMS {
            let target = curve17(&field, to);
            let imported = import_point(&target, &p).unwrap();
            assert!(
                core::ptr::eq(imported.curve(), &target),
                "{from:?} -> {to:?}"
            );
            assert!(imported.is_normalized(), "{from:?} -> {to:?}");
            assert_eq!(
                imported.encode(false),
                p.encode(false),
                "{from:?} -> {to:?}"
            );
            assert!(
                import_point(&target, &source.infinity())
                    .unwrap()
                    .is_infinity()
            );
        }
    }
}

#[test]
fn import_point_ignores_the_order_and_cofactor_as_bc_does() {
    let field = FpField::new(int(17)).unwrap();
    let source = curve17(&field, CoordinateSystem::Affine);
    let target = FpVarCurve::new(&field, &int(2), &int(2), None, None).unwrap();
    let p = source.create_point(&int(5), &int(1)).unwrap();
    assert_eq!(
        import_point(&target, &p).unwrap().encode(false),
        p.encode(false)
    );
}

#[test]
fn import_point_rejects_another_equation_or_another_field() {
    let field = FpField::new(int(17)).unwrap();
    let other_field = FpField::new(int(19)).unwrap();
    let source = curve17(&field, CoordinateSystem::Affine);
    let other_b = FpVarCurve::new(&field, &int(2), &int(3), None, None).unwrap();
    let other_q = FpVarCurve::new(&other_field, &int(2), &int(2), None, None).unwrap();
    let p = source.create_point(&int(5), &int(1)).unwrap();
    assert_eq!(
        import_point(&other_b, &p).unwrap_err(),
        AlgorithmError::CurveMismatch
    );
    assert_eq!(
        import_point(&other_q, &p).unwrap_err(),
        AlgorithmError::CurveMismatch
    );
}

#[test]
fn validate_point_accepts_infinity_and_points_of_the_subgroup_only() {
    // y² = x³ + x + 1 over F23 has 28 points; take the subgroup of order 7.
    let field = FpField::new(int(23)).unwrap();
    let curve = FpVarCurve::new(&field, &int(1), &int(1), Some(int(7)), Some(int(4))).unwrap();
    let p = curve.create_point(&int(3), &int(10)).unwrap();
    assert!(
        !p.multiply(&int(7)).is_infinity(),
        "(3, 10) lies outside the subgroup"
    );
    let q = p.multiply(&int(4));

    assert!(validate_point(&q).is_ok());
    assert!(validate_point(&curve.infinity()).is_ok());
    assert_eq!(
        validate_point(&p).unwrap_err(),
        AlgorithmError::InvalidPoint
    );
    let off_curve = curve.create_point(&int(3), &int(11)).unwrap();
    assert_eq!(
        validate_point(&off_curve).unwrap_err(),
        AlgorithmError::InvalidPoint
    );
}

#[test]
fn clean_point_imports_then_validates() {
    let field = FpField::new(int(17)).unwrap();
    let source = curve17(&field, CoordinateSystem::Jacobian);
    let target = curve17(&field, CoordinateSystem::Affine);
    let p = source
        .create_point(&int(5), &int(1))
        .unwrap()
        .multiply(&int(3));
    let cleaned = clean_point(&target, &p).unwrap();
    assert!(core::ptr::eq(cleaned.curve(), &target));
    assert_eq!(cleaned.encode(true), p.encode(true));

    let off_curve = source.create_point(&int(5), &int(2)).unwrap();
    assert_eq!(
        clean_point(&target, &off_curve).unwrap_err(),
        AlgorithmError::InvalidPoint
    );
    let other = FpVarCurve::new(&field, &int(2), &int(3), None, None).unwrap();
    assert_eq!(
        clean_point(&other, &p).unwrap_err(),
        AlgorithmError::CurveMismatch
    );
}

#[test]
fn montgomery_trick_inverts_a_batch_with_one_inversion_and_an_optional_scale() {
    let field = SECP256R1.field();
    let curve = SECP256R1.var_curve(&field);
    let one = (&curve).one();
    let values = elements(&one, 9);

    let mut inverses = values.clone();
    montgomery_trick(&mut inverses, None).unwrap();
    for (value, inverse) in values.iter().zip(&inverses) {
        assert!(value.multiply(inverse).is_one());
    }

    let scale = values[4].clone();
    let mut scaled = values.clone();
    montgomery_trick(&mut scaled, Some(&scale)).unwrap();
    for (value, inverse) in values.iter().zip(&scaled) {
        assert!(value.multiply(&scale).multiply(inverse).is_one());
    }

    let mut single = vec![values[2].clone()];
    montgomery_trick(&mut single, None).unwrap();
    assert!(single[0].multiply(&values[2]).is_one());

    let mut empty: Vec<FpFieldElement<'_>> = Vec::new();
    assert!(montgomery_trick(&mut empty, None).is_ok());
}

#[test]
fn montgomery_trick_rejects_zero_and_leaves_the_input_unchanged() {
    let field = FpField::new(int(17)).unwrap();
    let curve = curve17(&field, CoordinateSystem::Affine);
    let one = (&curve).one();
    let mut values = elements(&one, 4);
    values[2] = (&curve).zero();
    let before = values.clone();

    assert_eq!(
        montgomery_trick(&mut values, None),
        Err(AlgorithmError::NotInvertible)
    );
    assert!(values == before);

    let mut values = elements(&one, 4);
    let before = values.clone();
    assert_eq!(
        montgomery_trick(&mut values, Some(&(&curve).zero())),
        Err(AlgorithmError::NotInvertible)
    );
    assert!(values == before);
}

#[test]
fn normalize_all_scales_every_projective_point_to_z_one_in_every_system() {
    let field = FpField::new(int(17)).unwrap();
    for system in SYSTEMS {
        let curve = curve17(&field, system);
        let g = curve.create_point(&int(5), &int(1)).unwrap();
        let mut points: Vec<_> = (0..12).map(|k| g.multiply(&int(k))).collect();
        points.push(g.clone());
        let originals = points.clone();

        normalize_all(&mut points).unwrap();
        for (point, original) in points.iter().zip(&originals) {
            assert!(point == original, "{system:?}");
            assert!(point.is_normalized(), "{system:?}");
        }
        assert!(points[0].is_infinity(), "{system:?}");
    }
}

#[test]
fn normalize_all_works_on_the_constant_time_points_too() {
    let field = SECP256R1.field();
    let curve = SECP256R1.ct_curve(&field);
    let g = SECP256R1.ct_generator(&curve);
    let mut points: Vec<_> = (0..6).map(|k| g.multiply(&int(k))).collect();
    let originals = points.clone();

    normalize_all(&mut points).unwrap();
    for (point, original) in points.iter().zip(&originals) {
        assert!(point == original);
        assert!(point.projective_z().is_none_or(|z| z.is_one()));
    }
}

#[test]
fn normalize_all_rejects_mixed_curves_before_touching_the_slice() {
    let field = FpField::new(int(17)).unwrap();
    let jacobian = curve17(&field, CoordinateSystem::Jacobian);
    let other = FpVarCurve::new(&field, &int(2), &int(3), None, None)
        .unwrap()
        .with_coordinate_system(CoordinateSystem::Jacobian);
    let g = jacobian.create_point(&int(5), &int(1)).unwrap();
    let stranger = other.infinity().twice();
    let mut points = vec![g.multiply(&int(3)), stranger, g.multiply(&int(5))];
    let before: Vec<_> = points.iter().map(|p| p.z_coord(0)).collect();

    assert_eq!(
        normalize_all(&mut points),
        Err(AlgorithmError::CurveMismatch)
    );
    let after: Vec<_> = points.iter().map(|p| p.z_coord(0)).collect();
    assert!(before == after);

    let mut empty: Vec<tc_fp_curve_v2::FpVarPoint<'_>> = Vec::new();
    assert!(normalize_all(&mut empty).is_ok());
}

#[test]
fn every_algorithm_accepts_both_curve_sets_on_secp256r1() {
    let field = SECP256R1.field();
    let var_curve = SECP256R1
        .var_curve(&field)
        .with_coordinate_system(CoordinateSystem::Jacobian);
    let ct_curve = SECP256R1.ct_curve(&field);
    let h = SECP256R1.var_generator(&var_curve).multiply(&int(9));
    let g = SECP256R1.ct_generator(&ct_curve).multiply(&int(9));

    assert!(validate_point(&h).is_ok() && validate_point(&g).is_ok());
    assert_eq!(
        clean_point(&var_curve, &h).unwrap().encode(true),
        h.encode(true)
    );
    assert_eq!(
        clean_point(&ct_curve, &g).unwrap().encode(true),
        g.encode(true)
    );
    assert_eq!(h.encode(true), g.encode(true));
}
