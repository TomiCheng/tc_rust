use tc_macs::{Mac, MacInit};
use tc_params::KeyWithIvRef;
use tc_vmpc_mac::VmpcMac;

#[test]
fn matches_the_bouncy_castle_vector() {
    let key = [
        0x96, 0x61, 0x41, 0x0a, 0xb7, 0x97, 0xd8, 0xa9, 0xeb, 0x76, 0x7c, 0x21, 0x17, 0x2d, 0xf6,
        0xc7,
    ];
    let iv = [
        0x4b, 0x5c, 0x2f, 0x00, 0x3e, 0x67, 0xf3, 0x95, 0x57, 0xa8, 0xd2, 0x6f, 0x3d, 0xa2, 0xb1,
        0x55,
    ];
    let message = core::array::from_fn::<_, 256, _>(|index| index as u8);
    let mut mac = VmpcMac::new();
    mac.init(&KeyWithIvRef::new(&key, &iv)).unwrap();
    for chunk in message.chunks(7) {
        mac.update(chunk).unwrap();
    }

    let mut output = [0_u8; 20];
    mac.do_final(&mut output).unwrap();
    assert_eq!(
        output,
        [
            0x9b, 0xda, 0x16, 0xe2, 0xad, 0x0e, 0x28, 0x47, 0x74, 0xa3, 0xac, 0xbc, 0x88, 0x35,
            0xa8, 0x32, 0x6c, 0x11, 0xfa, 0xad,
        ]
    );
}
