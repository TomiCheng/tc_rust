    #[test]
    fn chunking_matches_whole_at_block_boundaries() {
        let message: Vec<u8> = (0..129).map(|i| i as u8).collect();
        for length in [0, 1, 63, 64, 65, 127, 128, 129] {
            let input = &message[..length];

            let mut whole_256 = Gost3411_2012_256Digest::new();
            whole_256.update(input);
            let mut expected_256 = [0u8; 32];
            whole_256.do_final(&mut expected_256);

            let mut chunked_256 = Gost3411_2012_256Digest::new();
            for chunk in input.chunks(7) {
                chunked_256.update(chunk);
            }
            let mut actual_256 = [0u8; 32];
            chunked_256.do_final(&mut actual_256);
            assert_eq!(actual_256, expected_256, "256-bit length {length}");

            let mut whole_512 = Gost3411_2012_512Digest::new();
            whole_512.update(input);
            let mut expected_512 = [0u8; 64];
            whole_512.do_final(&mut expected_512);

            let mut bytewise_512 = Gost3411_2012_512Digest::new();
            for byte in input {
                bytewise_512.update(core::slice::from_ref(byte));
            }
            let mut actual_512 = [0u8; 64];
            bytewise_512.do_final(&mut actual_512);
            assert_eq!(actual_512, expected_512, "512-bit length {length}");
        }
    }

    #[test]
    fn accessors_clone_chunking_and_reset() {
        let message: Vec<u8> = (0..257).map(|i| i as u8).collect();

        let mut whole = Gost3411_2012_512Digest::new();
        assert_eq!(whole.algorithm_name(), "GOST3411-2012-512");
        assert_eq!(whole.digest_size(), 64);
        assert_eq!(whole.byte_length(), 64);
        whole.update(&message);

        let mut cloned = whole.clone();
        let mut expected = [0u8; 64];
        let mut cloned_output = [0u8; 64];
        whole.do_final(&mut expected);
        cloned.do_final(&mut cloned_output);
        assert_eq!(cloned_output, expected);

        let mut chunked = Gost3411_2012_512Digest::new();
        for chunk in message.chunks(13) {
            chunked.update(chunk);
        }
        let mut actual = [0u8; 64];
        chunked.do_final(&mut actual);
        assert_eq!(actual, expected);

        let empty_after_reset = hex(&mut chunked, b"");
        let fresh_empty = hex(&mut Gost3411_2012_512Digest::new(), b"");
        assert_eq!(empty_after_reset, fresh_empty);

        let digest_256 = Gost3411_2012_256Digest::new();
        assert_eq!(digest_256.algorithm_name(), "GOST3411-2012-256");
        assert_eq!(digest_256.digest_size(), 32);
        assert_eq!(digest_256.byte_length(), 64);
    }
