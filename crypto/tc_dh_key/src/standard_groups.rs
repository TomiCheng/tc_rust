//! BC 的 `DHStandardGroups`：IETF 公布的 Diffie-Hellman 群組。每組都是安全質數 p、
//! g = 2、q = (p − 1) / 2；RFC 3526 與 RFC 7919 的群組另依 RFC 7919 與 FIPS 的建議值
//! 設定私鑰位元數 l，m 則照 BC 取 l 與 160 中較小者。
//!
//! 群組含堆積上的大數，不能寫成常數，所以每個群組是一個函式，呼叫時才從十六進位轉出。

use crate::DhParameters;
use alloc::vec::Vec;
use tc_bigint::{ArrayEncoding, PaddedBigUint};

/// BC 的 `SafePrimeGen2`：p、g = 2、q = p >> 1，與私鑰位元數 l（0 表示不指定）。變動時間：
/// 只處理公開的常數。
fn safe_prime_gen2(hex_p: &str, l: u32) -> DhParameters {
    let bytes: Vec<u8> = (0..hex_p.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex_p[i..i + 2], 16).expect("a hexadecimal constant"))
        .collect();
    let Ok(p) = PaddedBigUint::from_be(&bytes);
    let q = &p >> 1;
    DhParameters::new(p, PaddedBigUint::from(2u8))
        .with_q(q)
        .with_l(l)
}

