/// Expands the key into the round keys for the requested direction.
pub(crate) fn expand_key(for_encryption: bool, key: &[u8; KEY_BYTES]) -> [u32; ROUNDS] {
    // 前四個字先與系統參數 FK 相抵,之後就是一個滑動視窗。
    let mut window = [0_u32; 4];
    for ((word, chunk), fixed) in window.iter_mut().zip(key.chunks_exact(4)).zip(FK) {
        *word = u32::from_be_bytes(chunk.try_into().unwrap()) ^ fixed;
    }

    let mut round_keys = [0_u32; ROUNDS];
    for (round_key, constant) in round_keys.iter_mut().zip(CK) {
        *round_key = window[0] ^ t_prime(window[1] ^ window[2] ^ window[3] ^ constant);
        window = [window[1], window[2], window[3], *round_key];
    }

    // 解密就是同一組輪金鑰倒著用。
    if !for_encryption {
        round_keys.reverse();
    }
    round_keys
}

/// Runs the round loop; the direction is already encoded in `round_keys`.
pub(crate) fn process_block(
    round_keys: &[u32; ROUNDS],
    input: &[u8; BLOCK_BYTES],
    output: &mut [u8; BLOCK_BYTES],
) {
    let mut x = [0_u32; 4];
    for (word, chunk) in x.iter_mut().zip(input.chunks_exact(4)) {
        *word = u32::from_be_bytes(chunk.try_into().unwrap());
    }

    for round in round_keys.chunks_exact(4) {
        x[0] ^= t(x[1] ^ x[2] ^ x[3] ^ round[0]);
        x[1] ^= t(x[2] ^ x[3] ^ x[0] ^ round[1]);
        x[2] ^= t(x[3] ^ x[0] ^ x[1] ^ round[2]);
        x[3] ^= t(x[0] ^ x[1] ^ x[2] ^ round[3]);
    }

    // 最後的反序置換:輸出是 X35, X34, X33, X32。
    for (word, chunk) in x.iter().rev().zip(output.chunks_exact_mut(4)) {
        chunk.copy_from_slice(&word.to_be_bytes());
    }
}

/// The nonlinear substitution `tau`: the S-box applied to each byte.
fn tau(a: u32) -> u32 {
    let mut bytes = a.to_be_bytes();
    for byte in &mut bytes {
        *byte = SBOX[usize::from(*byte)];
    }
    u32::from_be_bytes(bytes)
}

/// The round mixer-substitution `T = L . tau`.
fn t(z: u32) -> u32 {
    let b = tau(z);
    b ^ b.rotate_left(2) ^ b.rotate_left(10) ^ b.rotate_left(18) ^ b.rotate_left(24)
}

/// The key-schedule mixer-substitution `T' = L' . tau`, which differs from
/// [`t`] only in the rotations of its linear part.
fn t_prime(z: u32) -> u32 {
    let b = tau(z);
    b ^ b.rotate_left(13) ^ b.rotate_left(23)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_s_box_is_a_permutation() {
        let mut seen = [false; 256];
        for &value in &SBOX {
            assert!(!seen[usize::from(value)], "duplicate entry {value:#04x}");
            seen[usize::from(value)] = true;
        }
    }

    #[test]
    fn the_decryption_schedule_is_the_encryption_schedule_reversed() {
        let key = [0xa5_u8; KEY_BYTES];
        let mut encryption = expand_key(true, &key);
        let decryption = expand_key(false, &key);
        encryption.reverse();
        assert_eq!(encryption, decryption);
    }
}
