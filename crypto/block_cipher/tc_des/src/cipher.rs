pub(crate) fn generate_working_key(encrypting: bool, key: &[u8; 8]) -> [u32; 32] {
    let mut new_key = [0_u32; 32];
    let mut pc1m = [false; 56];
    let mut pcr = [false; 56];

    for (j, &permuted_bit) in PC1.iter().enumerate() {
        let bit = usize::from(permuted_bit);
        pc1m[j] = key[bit >> 3] & BYTE_BIT[bit & 7] != 0;
    }

    for (round, &rotation) in TOTAL_ROTATIONS.iter().enumerate() {
        let first = if encrypting {
            round << 1
        } else {
            (15 - round) << 1
        };
        let second = first + 1;

        for (j, bit) in pcr[..28].iter_mut().enumerate() {
            let rotated = j + usize::from(rotation);
            *bit = pc1m[if rotated < 28 { rotated } else { rotated - 28 }];
        }
        for (offset, bit) in pcr[28..].iter_mut().enumerate() {
            let j = offset + 28;
            let rotated = j + usize::from(rotation);
            *bit = pc1m[if rotated < 56 { rotated } else { rotated - 28 }];
        }

        for j in 0..24 {
            if pcr[usize::from(PC2[j])] {
                new_key[first] |= BIG_BYTE[j];
            }
            if pcr[usize::from(PC2[j + 24])] {
                new_key[second] |= BIG_BYTE[j];
            }
        }
    }

    for i in (0..32).step_by(2) {
        let first = new_key[i];
        let second = new_key[i + 1];
        new_key[i] = ((first & 0x00fc0000) << 6)
            | ((first & 0x00000fc0) << 10)
            | ((second & 0x00fc0000) >> 10)
            | ((second & 0x00000fc0) >> 6);
        new_key[i + 1] = ((first & 0x0003f000) << 12)
            | ((first & 0x0000003f) << 16)
            | ((second & 0x0003f000) >> 4)
            | (second & 0x0000003f);
    }

    new_key
}

pub(crate) fn des_func(working_key: &[u32; 32], high: &mut u32, low: &mut u32) {
    let mut left = *high;
    let mut right = *low;

    let mut work = ((left >> 4) ^ right) & 0x0f0f0f0f;
    right ^= work;
    left ^= work << 4;
    work = ((left >> 16) ^ right) & 0x0000ffff;
    right ^= work;
    left ^= work << 16;
    work = ((right >> 2) ^ left) & 0x33333333;
    left ^= work;
    right ^= work << 2;
    work = ((right >> 8) ^ left) & 0x00ff00ff;
    left ^= work;
    right ^= work << 8;
    right = right.rotate_left(1);
    work = (left ^ right) & 0xaaaaaaaa;
    left ^= work;
    right ^= work;
    left = left.rotate_left(1);

    for round in 0..8 {
        work = right.rotate_right(4) ^ working_key[round * 4];
        let mut fval = SP7[(work & 0x3f) as usize]
            | SP5[((work >> 8) & 0x3f) as usize]
            | SP3[((work >> 16) & 0x3f) as usize]
            | SP1[((work >> 24) & 0x3f) as usize];
        work = right ^ working_key[round * 4 + 1];
        fval |= SP8[(work & 0x3f) as usize]
            | SP6[((work >> 8) & 0x3f) as usize]
            | SP4[((work >> 16) & 0x3f) as usize]
            | SP2[((work >> 24) & 0x3f) as usize];
        left ^= fval;

        work = left.rotate_right(4) ^ working_key[round * 4 + 2];
        fval = SP7[(work & 0x3f) as usize]
            | SP5[((work >> 8) & 0x3f) as usize]
            | SP3[((work >> 16) & 0x3f) as usize]
            | SP1[((work >> 24) & 0x3f) as usize];
        work = left ^ working_key[round * 4 + 3];
        fval |= SP8[(work & 0x3f) as usize]
            | SP6[((work >> 8) & 0x3f) as usize]
            | SP4[((work >> 16) & 0x3f) as usize]
            | SP2[((work >> 24) & 0x3f) as usize];
        right ^= fval;
    }

    right = right.rotate_right(1);
    work = (left ^ right) & 0xaaaaaaaa;
    left ^= work;
    right ^= work;
    left = left.rotate_right(1);
    work = ((left >> 8) ^ right) & 0x00ff00ff;
    right ^= work;
    left ^= work << 8;
    work = ((left >> 2) ^ right) & 0x33333333;
    right ^= work;
    left ^= work << 2;
    work = ((right >> 16) ^ left) & 0x0000ffff;
    left ^= work;
    right ^= work << 16;
    work = ((right >> 4) ^ left) & 0x0f0f0f0f;
    left ^= work;
    right ^= work << 4;

    *high = right;
    *low = left;
}
