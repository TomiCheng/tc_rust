//! The standardized GOST 28147 S-boxes.
//!
//! A table is eight rows of sixteen nibbles, laid out flat and row-major, the
//! same form Bouncy Castle passes around. Engines index it as
//! `table[row * COLUMNS + nibble]`.
//!
//! These are plain byte constants rather than a validated type: parameters
//! carry bytes, and checking them is the engine's job.

/// Rows in a table, one per four-bit slice of the round word.
pub const ROWS: usize = 8;
/// Entries per row: one for every nibble value.
pub const COLUMNS: usize = 16;
/// Length of a table in bytes.
pub const BYTES: usize = ROWS * COLUMNS;

