//! 移植自 zlib 1.3.2 的 `inftrees.c`：由碼長建出解碼用的查表。

const MAXBITS: usize = 15;

pub(super) const ENOUGH_LENS: usize = 852;
pub(super) const ENOUGH_DISTS: usize = 592;
pub(super) const ENOUGH: usize = ENOUGH_LENS + ENOUGH_DISTS;

/// 查表的一格。`op` 的意義：
/// `0` 字面值、`0000tttt` 子表（`tttt` 是索引位元數）、`0001eeee` 長度或距離
/// （`eeee` 是額外位元數）、`01100000` 區塊結束、`01000000` 無效碼。
#[derive(Clone, Copy, Debug, Default)]
pub(super) struct Code {
    pub(super) op: u8,
    pub(super) bits: u8,
    pub(super) val: u16,
}

const fn c(op: u8, bits: u8, val: u16) -> Code {
    Code { op, bits, val }
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum CodeType {
    Codes,
    Lens,
    Dists,
}

