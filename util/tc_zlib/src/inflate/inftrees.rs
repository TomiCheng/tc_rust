/// 由 `lens` 建出查表，寫進 `table[*next..]`；回傳後 `*next` 指向下一個空位，
/// `*bits` 是根表實際的索引位元數。
///
/// 回傳 `0` 成功、`-1` 碼長無效、`1` 表格空間不足。
pub(super) fn inflate_table(
    kind: CodeType,
    lens: &[u16],
    table: &mut [Code],
    next: &mut usize,
    bits: &mut u32,
    work: &mut [u16],
) -> i32 {
    let mut count = [0u16; MAXBITS + 1];
    let mut offs = [0u16; MAXBITS + 1];

    for &len in lens {
        count[len as usize] += 1;
    }

    let mut root = *bits;
    let mut max = MAXBITS as u32;
    while max >= 1 {
        if count[max as usize] != 0 {
            break;
        }
        max -= 1;
    }
    if root > max {
        root = max;
    }
    if max == 0 {
        let here = c(64, 1, 0);
        table[*next] = here;
        table[*next + 1] = here;
        *next += 2;
        *bits = 1;
        return 0;
    }
    let mut min = 1u32;
    while min < max {
        if count[min as usize] != 0 {
            break;
        }
        min += 1;
    }
    if root < min {
        root = min;
    }

    let mut left = 1i32;
    for &n in &count[1..] {
        left <<= 1;
        left -= i32::from(n);
        if left < 0 {
            return -1;
        }
    }
    if left > 0 && (kind == CodeType::Codes || max != 1) {
        return -1;
    }

    offs[1] = 0;
    for len in 1..MAXBITS {
        offs[len + 1] = offs[len] + count[len];
    }

    for (sym, &len) in lens.iter().enumerate() {
        if len != 0 {
            work[offs[len as usize] as usize] = sym as u16;
            offs[len as usize] += 1;
        }
    }

    let (base, extra, matched): (&[u16], &[u16], u32) = match kind {
        CodeType::Codes => (&[], &[], 20),
        CodeType::Lens => (&LBASE, &LEXT, 257),
        CodeType::Dists => (&DBASE, &DEXT, 0),
    };

    let start = *next;
    let mut huff = 0u32;
    let mut sym = 0usize;
    let mut len = min;
    let mut cur = start;
    let mut curr = root;
    let mut drop = 0u32;
    let mut low = u32::MAX;
    let mut used = 1u32 << root;
    let mask = used - 1;

    let too_big = |used: u32| {
        (kind == CodeType::Lens && used as usize > ENOUGH_LENS)
            || (kind == CodeType::Dists && used as usize > ENOUGH_DISTS)
    };
    if too_big(used) {
        return 1;
    }

    loop {
        let symbol = u32::from(work[sym]);
        let here = if symbol + 1 < matched {
            c(0, (len - drop) as u8, symbol as u16)
        } else if symbol >= matched {
            let at = (symbol - matched) as usize;
            c(extra[at] as u8, (len - drop) as u8, base[at])
        } else {
            c(32 + 64, (len - drop) as u8, 0)
        };

        let incr = 1u32 << (len - drop);
        let mut fill = 1u32 << curr;
        min = fill;
        loop {
            fill -= incr;
            table[cur + ((huff >> drop) + fill) as usize] = here;
            if fill == 0 {
                break;
            }
        }

        let mut incr = 1u32 << (len - 1);
        while huff & incr != 0 {
            incr >>= 1;
        }
        if incr != 0 {
            huff &= incr - 1;
            huff += incr;
        } else {
            huff = 0;
        }

        sym += 1;
        count[len as usize] -= 1;
        if count[len as usize] == 0 {
            if len == max {
                break;
            }
            len = u32::from(lens[work[sym] as usize]);
        }

        if len > root && (huff & mask) != low {
            if drop == 0 {
                drop = root;
            }
            cur += min as usize;

            curr = len - drop;
            let mut left = 1i32 << curr;
            while curr + drop < max {
                left -= i32::from(count[(curr + drop) as usize]);
                if left <= 0 {
                    break;
                }
                curr += 1;
                left <<= 1;
            }

            used += 1u32 << curr;
            if too_big(used) {
                return 1;
            }

            low = huff & mask;
            table[start + low as usize] = c(curr as u8, root as u8, (cur - start) as u16);
        }
    }

    if huff != 0 {
        table[cur + huff as usize] = c(64, (len - drop) as u8, 0);
    }

    *next = start + used as usize;
    *bits = root;
    0
}

